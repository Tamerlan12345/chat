// Имя файла, который сотрудник скачивает из обычной переписки (вложение
// сообщения), а не из сеанса удалённого доступа.
//
// Раньше у обычных вложений такой проверки не было вовсе: имя для сохранения
// бралось из текста сообщения как есть — отправитель мог вписать туда что
// угодно, вплоть до скрытых управляющих символов направления письма. Путь
// удалённого стола (received-file.js) эту задачу уже решает: то же самое
// правило — единственный список опасных расширений и одна и та же логика
// очистки имени — переиспользуется здесь, а не заводится заново.
//
// Модуль чистый: Electron не импортируется, поэтому в тестах не нужен
// поддельный 'electron'.

const { planReceivedFileName, isDangerousFileName } = require('./received-file');

// Итоговое имя для сохранения: управляющие символы и символы направления
// текста вырезаны, хвостовые точки/пробелы и зарезервированные имена Windows
// обезврежены, а опасное расширение получает дополнительный «.txt» — как и
// при получении файла по удалённому столу.
function safeDownloadName(name) {
  return planReceivedFileName(name).name;
}

// Тот же список расширений, что и у входящих файлов удалённого стола —
// второго списка нет и не должно быть.
function isDangerousExtension(name) {
  return isDangerousFileName(name);
}

module.exports = {
  safeDownloadName,
  isDangerousExtension
};
