package com.openmychat.mobile.ui.navigation

/**
 * Подписи нижней панели не растут выше 1.3x (рекомендация Material для панелей), а внутри этого
 * предела ещё и ужимаются до [MIN_SP], чтобы слово всегда помещалось целиком.
 *
 * Компромисс доступности: при системном шрифте 2.0 подпись вкладки получается меньше, чем просит
 * пользователь; взамен четыре вкладки читаются полностью и остаются нажимаемыми. Иконки и сами
 * вкладки при этом не уменьшаются, а полный текст остаётся в описании для TalkBack.
 *
 * Ширина: панель 360dp / 4 вкладки = 90dp на вкладку. «Объявления» (10 знаков, около 0,55 em на
 * знак) при 12sp x 1,3 = 15,6sp занимает около 86dp и упирается в край; при шрифте 2.0 без предела
 * было бы 24sp, около 132dp. Автоподбор размера в пределах 8–15,6sp гарантирует, что слово поместится.
 */
object NavLabelScale {
    const val MAX = 1.3f
    const val MIN_SP = 8f

    fun cap(fontScale: Float): Float = fontScale.coerceAtMost(MAX)
}
