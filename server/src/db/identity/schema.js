// Таблицы с собственным счётчиком id. После переноса готовых строк счётчик
// надо подвинуть за наибольший занятый id, иначе первая же новая запись
// столкнётся с существующей.
const SEQUENCED_TABLES = ['roles', 'departments', 'users', 'pending_devices', 'audit_logs', 'security_alerts'];

// Колонки, появившиеся после первого выпуска. CREATE TABLE IF NOT EXISTS
// существующую таблицу не трогает, поэтому их добавляет отдельный шаг.
const ADDED_COLUMNS = [
  // Секрет устройства: вход без пароля возможен, только если клиент его
  // предъявил. Номер устройства сам по себе больше не пропуск.
  ['device_pairings', 'secret_hash', 'TEXT'],
  ['device_pairings', 'secret_token_version', 'INTEGER'],
  // Секрет теперь привязан к тому, кто его claim'ил (secret_user_id), а не
  // только к текущему владельцу устройства: перепривязка устройства другому
  // сотруднику раньше молча наследовала чужой секрет (аудит, находка №1).
  // secret_expires_at и secret_auth_time закрывают находку №9: секрет
  // перестаёт быть вечным бессрочным ключом и не сбрасывает auth_time при
  // каждом входе по устройству.
  ['device_pairings', 'secret_user_id', 'INTEGER'],
  ['device_pairings', 'secret_expires_at', 'TEXT'],
  ['device_pairings', 'secret_auth_time', 'TEXT'],
  // Цепочка отпечатков журнала аудита: изменённая или удалённая запись
  // рвёт цепочку, и проверка это замечает.
  ['audit_logs', 'prev_hash', 'TEXT'],
  ['audit_logs', 'hash', 'TEXT']
];

async function columnsOf(driver, table) {
  if (driver.dialect === 'postgres') {
    const rows = await driver.all(
      'SELECT column_name AS name FROM information_schema.columns WHERE table_name = $1',
      [table]
    );
    return new Set(rows.map((r) => r.name));
  }
  const rows = await driver.all(`PRAGMA table_info(${table})`);
  return new Set(rows.map((r) => r.name));
}

async function createSchema(driver) {
  await driver.exec(DDL[driver.dialect]);
  for (const [table, column, type] of ADDED_COLUMNS) {
    const existing = await columnsOf(driver, table);
    if (!existing.has(column)) await driver.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${type}`);
  }
  // Ранняя сборка суточного предела (sec5) создавала журнал неудач без
  // суррогатного id — первичный ключ столбцом не добавить. Журнал живёт сутки и
  // восстанавливается сам, поэтому такую таблицу проще пересоздать.
  const failureLogColumns = await columnsOf(driver, 'login_failure_log');
  if (failureLogColumns.size && !failureLogColumns.has('id')) {
    await driver.exec('DROP TABLE login_failure_log');
    await driver.exec(DDL[driver.dialect]);
  }
}

async function resyncSequences(driver) {
  if (driver.dialect !== 'postgres') return; // SQLite ведёт счётчик сам
  for (const table of SEQUENCED_TABLES) {
    const row = await driver.get(`SELECT COALESCE(MAX(id), 0) + 1 AS next FROM ${table}`);
    const next = Number(row?.next || 1);
    await driver.exec(`ALTER TABLE ${table} ALTER COLUMN id RESTART WITH ${next}`);
  }
}

module.exports = { DDL, SEQUENCED_TABLES, createSchema, resyncSequences };
