// Схема хранилища учётных записей. Держится в одном месте и в двух диалектах:
// всё, кроме объявления таблиц, написано так, чтобы работать в обоих —
// параметры вида $1, ON CONFLICT, RETURNING, время строкой ISO-8601.
//
// Время намеренно хранится текстом, а не timestamptz: весь остальной код
// проекта оперирует new Date().toISOString(), и перевод на родной тип
// PostgreSQL означал бы, что одни и те же поля приходят то строкой, то
// объектом Date, в зависимости от того, где выполнен запрос. Сравнение и
// сортировка ISO-8601 в UTC совпадают с лексикографическими, поэтому ничего
// не теряется.
//
// Логические признаки (is_active, must_change_password) хранятся как INTEGER
// 0/1, а не BOOLEAN, по той же причине: весь код сравнивает их с 1.

